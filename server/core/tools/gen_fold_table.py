#!/usr/bin/env python3
"""Generate fold_table.inc — the C++ ASCII-fold table for alive_core.

Maps every Unicode codepoint >127 whose NFKD decomposition contains ASCII
bytes to the lowercase ASCII result of ``NFKD(cp).encode('ascii','ignore')``.
Codepoints that fold to nothing (Arabic, Devanagari, CJK, ...) are absent
from the table and are skipped entirely by the C++ normalizer — exactly the
semantics of Python's ``str.encode('ascii', 'ignore')``.

Run by CMake at configure time:

    python3 gen_fold_table.py <output.inc>

The table is generated with the same Python/unicodedata version that runs the
parity tests, so C++ normalization is bit-identical to alive_core_ref.py.
"""

import sys
import unicodedata

HEADER = """\
// AUTO-GENERATED by tools/gen_fold_table.py - do not edit.
// codepoint -> lowercase ASCII fold (NFKD -> encode('ascii','ignore') -> lower())
"""

FOOTER = """\
static const unsigned kFoldTableSize = sizeof(kFoldTable) / sizeof(kFoldTable[0]);
"""


def fold(cp: int) -> str:
    decomp = unicodedata.normalize("NFKD", chr(cp))
    return decomp.encode("ascii", "ignore").decode("ascii").lower()


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: gen_fold_table.py <output.inc>")
    out_path = sys.argv[1]

    rows = []
    for cp in range(0x80, 0x110000):
        try:
            folded = fold(cp)
        except ValueError:
            continue  # lone surrogate range etc. — chr() can still fail on some builds
        if folded:
            rows.append((cp, folded))

    with open(out_path, "w", encoding="ascii") as f:
        f.write(HEADER)
        f.write("static const std::pair<unsigned int, const char*> kFoldTable[] = {\n")
        for cp, folded in rows:
            esc = folded.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'    {{0x{cp:05X}u, "{esc}"}},\n')
        f.write("};\n")
        f.write(FOOTER)
    print(f"gen_fold_table: {len(rows)} codepoints -> {out_path}")


if __name__ == "__main__":
    main()
