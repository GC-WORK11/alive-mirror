#!/usr/bin/env python3
"""Generate ef_table.inc — the C++ per-mode emission-factor table.

Resolves each canonical emissions class in ref_series.EMISSION_CLASSES
through server/emissions.py's own chain (emission_factors({"class": cls})
→ class-default fuel, year "not_sure" → Delhi fleet prior) and emits the
resolved g/km band at REF_SPEED_MPS plus the per-pkm flag, occupancy, and
the mode-alias map — as hexfloat literals so the C++ constants are
bit-identical to the Python floats (float.hex() round-trips through the
C99/C++17 strtod contract).

Run by CMake at configure time:

    python3 gen_ef_table.py <output.inc>

Generating from emissions.py itself (rather than checking in a hand-
copied table) means the C++ lookup cannot silently drift from the
production factors — a table edit there is a rebuild here, and the
parity tests assert the full chain to 1e-9.
"""

import os
import sys

_TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
_CORE_DIR = os.path.dirname(_TOOLS_DIR)
_SERVER_DIR = os.path.dirname(_CORE_DIR)
for _p in (_SERVER_DIR, _CORE_DIR):
    if _p not in sys.path:
        sys.path.insert(0, _p)

HEADER = """\
// AUTO-GENERATED by tools/gen_ef_table.py - do not edit.
// Resolved emission-factor bands per mode: emissions.emission_factors(
// {"class": cls}) fleet-prior defaults, g/km at kEmRefSpeedMps, warm.
// Pollutant order matches enum Pol (co2, pm25, nox); doubles are C
// hexfloats (float.hex()) so they are bit-identical to the Python table.
"""


def _hx(v: float) -> str:
    """Python float -> C hexfloat literal (exact double round-trip)."""
    import math
    if not math.isfinite(v):
        sys.exit(f"gen_ef_table: non-finite value {v!r} — hexfloat literals "
                 "cannot express inf/nan")
    return float(v).hex()


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: gen_ef_table.py <output.inc>")
    out_path = sys.argv[1]

    try:
        import ref_series
    except ImportError as e:
        sys.exit(f"gen_ef_table: cannot import ref_series: {e}")
    try:
        table = ref_series.emission_mode_table()   # imports emissions.py
    except Exception as e:
        sys.exit(f"gen_ef_table: emissions.py resolution failed: {e}")

    with open(out_path, "w", encoding="ascii") as f:
        f.write(HEADER)
        f.write("static const EmModeRow kEmModeTable[] = {\n")
        for cls in ref_series.EMISSION_CLASSES:
            row = table[cls]
            bands = ", ".join(
                "{{{},{},{}}}".format(*(_hx(x) for x in row["bands"][pol]))
                for pol in ("co2", "pm25", "nox"))
            f.write(
                f'    {{"{cls}", {"true" if row["per_pkm"] else "false"}, '
                f'{_hx(row["occupancy"])}, {{{bands}}}}},\n')
        f.write("};\n\n")
        f.write("static const EmAliasRow kEmAliasTable[] = {\n")
        for alias in sorted(ref_series.EMISSION_MODE_ALIASES):
            f.write(f'    {{"{alias}", '
                    f'"{ref_series.EMISSION_MODE_ALIASES[alias]}"}},\n')
        f.write("};\n")
    print(f"gen_ef_table: {len(table)} modes + "
          f"{len(ref_series.EMISSION_MODE_ALIASES)} aliases -> {out_path}")


if __name__ == "__main__":
    main()
