const { withXcodeProject, withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

/* iCloud backup exclusion — the same owner ask as withBackupRules.js,
   iOS side: device stores restore through the user's own iCloud backup
   on a new phone. Everything in Documents/ backs up by default — that is
   the restore path and stays untouched. What must NOT ride along is the
   MapLibre offline store (offline tile pack + ambient cache, ~30–190 MB
   of regenerable tiles) living under Library/Application Support — which
   iCloud backs up too.

   expo-file-system exposes no NSURLIsExcludedFromBackupKey API, so this
   plugin injects one tiny ObjC file whose +load marks the .mapbox dir
   excluded — at image load and again ~30 s in, because MLRN creates the
   dir lazily on first map init. The attribute on the directory covers
   every file inside, including cache.db deleted and recreated later. */

const SRC = `#import <Foundation/Foundation.h>

/* Auto-generated by plugins/withBackupExclusion.js — regenerable map
   store must not inflate the user's iCloud backup. The real stores in
   Documents/ (ledger, daylog, daysum, settings, consent, vehicle,
   places, outbox, events) keep backing up on purpose — they are the
   profile-based restore payload. */
@interface AliveBackupExclusion : NSObject
@end

@implementation AliveBackupExclusion

+ (void)load {
  [self apply];
  /* the offline DB is created lazily after maplibre's first init —
     reapply once shortly after launch so a fresh install's pack is
     covered too (the attribute is on the directory; contents inherit) */
  dispatch_after(dispatch_time(DISPATCH_TIME_NOW, (int64_t)(30 * NSEC_PER_SEC)),
                 dispatch_get_main_queue(), ^{
    [self apply];
  });
}

+ (void)apply {
  NSFileManager *fm = NSFileManager.defaultManager;
  NSURL *appSupport =
      [[fm URLsForDirectory:NSApplicationSupportDirectory
                  inDomains:NSUserDomainMask] lastObject];
  NSMutableArray<NSURL *> *roots = [NSMutableArray arrayWithObject:appSupport];
  NSString *bundleId = NSBundle.mainBundle.bundleIdentifier;
  if (bundleId != nil) {
    [roots addObject:[appSupport URLByAppendingPathComponent:bundleId
                                               isDirectory:YES]];
  }
  for (NSURL *root in roots) {
    NSURL *mapbox =
        [root URLByAppendingPathComponent:@".mapbox" isDirectory:YES];
    [mapbox setResourceValue:@YES
                      forKey:NSURLIsExcludedFromBackupKey
                       error:nil];
  }
}

@end
`;

const FILE_NAME = "AliveBackupExclusion.m";

module.exports = function withBackupExclusion(config) {
  config = withDangerousMod(config, [
    "ios",
    async (c) => {
      const appDir = path.join(
        c.modRequest.platformProjectRoot,
        c.modRequest.projectName,
      );
      fs.writeFileSync(path.join(appDir, FILE_NAME), SRC);
      return c;
    },
  ]);
  return withXcodeProject(config, (c) => {
    const project = c.modResults;
    const group = project.findPBXGroupKey({ name: c.modRequest.projectName });
    if (!project.hasFile(FILE_NAME) && group) {
      project.addSourceFile(
        `${c.modRequest.projectName}/${FILE_NAME}`,
        {},
        group,
      );
    }
    return c;
  });
};
